#!/usr/bin/env node
// ESARR live benchmark: measures the bundled library against (a) hand-rolled
// ES3 loops (the "no shim" baseline) and (b) MDN-style polyfills (the stock
// competitor) — in the REAL Adobe engine via ILLUSTRATOR_COM_TOOL.py.
// Reports medians per (method x array size x implementation).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

var ROOT = dirname(fileURLToPath(import.meta.url));
var PROJECT = join(ROOT, '..');
var DIST = join(PROJECT, 'dist');
var VENDOR = join(DIST, 'vendor-esarr.js');
var TOOL = 'C:/Program Files/Adobe/Adobe Illustrator 2026/Presets/en_US/Scripts/agent-skills/illustrator-com-automation-skill/comtool/ILLUSTRATOR_COM_TOOL.py';

if (!existsSync(VENDOR)) { console.error('benchmark: build first (npm run build)'); process.exit(1); }
if (!existsSync(TOOL)) { console.error('benchmark: COM tool not found'); process.exit(1); }

var SIZES = [256, 2000, 8000];
var REPS = 9;

var probeDir = join(process.env.TEMP || '', 'esarr-bench');
mkdirSync(probeDir, { recursive: true });
var mdnPath = join(probeDir, 'esarr-mdn-baseline.jsx');
var probePath = join(probeDir, 'esarr-bench-battery.jsx');

execFileSync(process.execPath, [esbuildBin(), join(ROOT, 'mdn-baseline.ts'),
  '--bundle', '--outfile=' + mdnPath,
  '--format=iife', '--global-name=MDN', '--platform=neutral', '--target=es5',
  '--log-level=warning'], { stdio: 'inherit' });

var vendorForProbe = VENDOR.replace(/\\/g, '/');
var mdnForProbe = mdnPath.replace(/\\/g, '/');
var sizesJson = JSON.stringify(SIZES);

var probeSrc = [
  '#target illustrator',
  '// generated by tests/benchmark.mjs - do not edit',
  '$.evalFile(File("' + vendorForProbe + '"));',
  '$.evalFile(File("' + mdnForProbe + '"));',
  'var B_SIZES = ' + sizesJson + ';',
  'var B_REPS = ' + REPS + ';',
  'function bMedian(t) { var s = t.slice().sort(function (a, b) { return a - b; }); return s[Math.floor(s.length / 2)]; }',
  'function bTime(fn) {',
  '  var best = 1e15, i, d, v = 0;',
  '  for (i = 0; i < 2; i++) { v = fn(); }',
  '  for (i = 0; i < B_REPS; i++) {',
  '    $.hiresTimer;',
  '    fn();',
  '    d = $.hiresTimer;',
  '    if (d > 0 && d < best) { best = d; }',
  '    v += 1;',
  '  }',
  '  return best;',
  '}',
  'var bOut = [];',
  'var bArr, bI, bJ;',
  'for (bI = 0; bI < B_SIZES.length; bI++) {',
  '  var bN = B_SIZES[bI];',
  '  bArr = [];',
  '  for (bJ = 0; bJ < bN; bJ++) { bArr[bArr.length] = bJ; }',
  '  var bRow = { n: bN, lanes: [] };',
  '  var bItem = function (name, oursFn, mdnFn, handFn) {',
  '    var ours = bTime(oursFn);',
  '    var mdn = bTime(mdnFn);',
  '    var hand = bTime(handFn);',
  '    bRow.lanes[bRow.lanes.length] = { name: name, oursUs: ours, mdnUs: mdn, handUs: hand,',
  '      vsHand: hand > 0 ? hand / ours : 0, vsMdn: mdn > 0 ? mdn / ours : 0 };',
  '  };',
  '  var bSum = function (a, v) { return a + v; };',
  '  var bInc = function (v) { return v + 1; };',
  '  var bEven = function (v) { return v % 2 === 0; };',
  '  var bNeg = function (v) { return v < 0; };',
  '  bItem("forEach", function () { ESARR.forEach(bArr, bSum); },',
  '    function () { MDN.mdnForEach(bArr, bSum); },',
  '    function () { var s = 0, q; for (q = 0; q < bN; q++) { s += bArr[q]; } return s; });',
  '  bItem("map", function () { ESARR.map(bArr, bInc); },',
  '    function () { MDN.mdnMap(bArr, bInc); },',
  '    function () { var r = new Array(bN), q; for (q = 0; q < bN; q++) { r[q] = bArr[q] + 1; } return r; });',
  '  bItem("filter", function () { ESARR.filter(bArr, bEven); },',
  '    function () { MDN.mdnFilter(bArr, bEven); },',
  '    function () { var r = [], q; for (q = 0; q < bN; q++) { if (bArr[q] % 2 === 0) { r.push(bArr[q]); } } return r; });',
  '  bItem("every", function () { ESARR.every(bArr, bInc); },',
  '    function () { MDN.mdnEvery(bArr, bInc); },',
  '    function () { var ok = true, q; for (q = 0; q < bN; q++) { if (!(bArr[q] + 1)) { ok = false; break; } } return ok; });',
  '  bItem("some", function () { ESARR.some(bArr, bNeg); },',
  '    function () { MDN.mdnSome(bArr, bNeg); },',
  '    function () { var f = false, q; for (q = 0; q < bN; q++) { if (bArr[q] < 0) { f = true; break; } } return f; });',
  '  bItem("indexOf-miss", function () { ESARR.indexOf(bArr, -1); },',
  '    function () { MDN.mdnIndexOf(bArr, -1); },',
  '    function () { var f = -1, q; for (q = 0; q < bN; q++) { if (bArr[q] === -1) { f = q; break; } } return f; });',
  '  bItem("lastIndexOf", function () { ESARR.lastIndexOf(bArr, 0); },',
  '    function () { MDN.mdnLastIndexOf(bArr, 0); },',
  '    function () { var f = -1, q; for (q = bN - 1; q >= 0; q--) { if (bArr[q] === 0) { f = q; break; } } return f; });',
  '  bItem("reduce", function () { ESARR.reduce(bArr, bSum, 0); },',
  '    function () { MDN.mdnReduce(bArr, bSum, 0); },',
  '    function () { var s = 0, q; for (q = 0; q < bN; q++) { s += bArr[q]; } return s; });',
  '  bItem("reduceRight", function () { ESARR.reduceRight(bArr, bSum, 0); },',
  '    function () { MDN.mdnReduceRight(bArr, bSum, 0); },',
  '    function () { var s = 0, q; for (q = bN - 1; q >= 0; q--) { s += bArr[q]; } return s; });',
  '  bOut[bOut.length] = bRow;',
  '}',
  'var bReport = { engine: $.version, host: app.name + " " + app.version, sizes: B_SIZES, reps: B_REPS, rows: bOut };',
  'bReport;'
].join('\n');
writeFileSync(probePath, probeSrc);

console.log('benchmark: running ' + SIZES.length + ' sizes x 9 lanes x 3 impls in Illustrator...');
var pyOut;
try {
  pyOut = execFileSync('python', [TOOL, 'eval', '--file', probePath.replace(/\\/g, '/')], {
    encoding: 'utf8', timeout: 300000
  });
} catch (e) {
  console.error('benchmark: COM tool failed: ' + String((e.stdout || e.message) + '').slice(0, 2000));
  process.exit(1);
}
var env;
try { env = JSON.parse(pyOut.trim()); } catch (e) { console.error('benchmark: tool output not JSON: ' + pyOut.slice(0, 500)); process.exit(1); }
if (!env.ok || !env.result || !env.result.result) {
  console.error('benchmark: tool/engine error: ' + JSON.stringify(env).slice(0, 1500));
  process.exit(1);
}
var report = env.result.result;

console.log('');
console.log('ESARR live benchmark — ' + report.host + ' / ExtendScript ' + report.engine + ', best-of-' + report.reps + ' medians (us):');
console.log('');
console.log('lane           n     ours(us)  mdn(us)   hand(us)  vsMDN    vsHand');
for (var r = 0; r < report.rows.length; r++) {
  var row = report.rows[r];
  for (var l = 0; l < row.lanes.length; l++) {
    var it = row.lanes[l];
    var pad = function (s, w) {
      var str = String(Math.round(s));
      while (str.length < w) { str = ' ' + str; }
      return str;
    };
    console.log(padName(it.name, 12) + pad(row.n, 6) + pad(it.oursUs, 9) + pad(it.mdnUs, 9) + pad(it.handUs, 9) +
      '  ' + it.vsMdn.toFixed(2) + 'x' + pad(it.vsHand, 6) + 'x');
  }
}
console.log('');
console.log('vsMDN > 1 = ESARR faster than the MDN-style polyfill; vsHand > 1 = faster than the hand-rolled loop.');

function padName(s, w) {
  while (s.length < w) { s = s + ' '; }
  return s;
}

function esbuildBin() {
  var direct = join(PROJECT, 'node_modules', 'esbuild', 'bin', 'esbuild');
  if (existsSync(direct)) { return direct; }
  var cacheDirs = [
    join(process.env.LOCALAPPDATA || '', 'npm-cache', '_npx'),
    join(process.env.USERPROFILE || '', 'AppData', 'Local', 'npm-cache', '_npx')
  ];
  for (var c = 0; c < cacheDirs.length; c++) {
    try {
      var entries = readdirSync(cacheDirs[c]);
      for (var j = 0; j < entries.length; j++) {
        var p = join(cacheDirs[c], entries[j], 'node_modules', 'esbuild', 'bin', 'esbuild');
        if (existsSync(p)) { return p; }
      }
    } catch (ignore) {}
  }
  return 'npx esbuild';
}
