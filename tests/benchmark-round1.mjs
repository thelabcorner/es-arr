function rowValue(laneName, field, s) {
  var rows = bySize[s] || [];
  for (var i = 0; i < rows.length; i++) {
    if (rows[i].lane === laneName && rows[i][field] !== undefined && rows[i][field] > 0) {
      return rows[i][field];
    }
  }
  return -1;
}

// Power-law extrapolation: v(nn) = v(s2) * (nn/s2)^exponent, where exponent
// is derived from the two largest measured sizes for this lane+column.
// Returns -1 when no basis exists (fewer than 2 measured points).
function extValue(laneName, field, nn) {
  var sizes = [];
  for (var s in bySize) {
    var sn = parseInt(s, 10);
    if (rowValue(laneName, field, sn) > 0) { sizes[sizes.length] = sn; }
  }
  sizes.sort(function (a, b) { return a - b; });
  if (sizes.length < 2) { return -1; }
  var s1 = sizes[sizes.length - 2];
  var s2 = sizes[sizes.length - 1];
  var v1 = rowValue(laneName, field, s1);
  var v2 = rowValue(laneName, field, s2);
  if (v1 <= 0 || v2 <= 0 || nn <= s2) { return -1; }
  var exponent = Math.log(v2 / v1) / Math.log(s2 / s1);
  return Math.round(v2 * Math.pow(nn / s2, exponent));
}

