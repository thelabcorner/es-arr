#!/usr/bin/env node
// ESARR ROUND-1 benchmark (swarm task T6): native-backed lanes vs engine
// builtins vs pure-JSX ESARR vs hand-rolled loops, live in Illustrator 30.6.0
// via ILLUSTRATOR_COM_TOOL.py, on the reclaimed bench instance (PID 100964).
//
// Methodology (design doc §7 + baseline contract):
//   - primed $.hiresTimer, medians-of-9 (fast sizes) / -of-3 (16k+, 7s ops),
//     2 warmups, outlier rejection (samples <= 0 or > 1e8 us dropped)
//   - per-(size, lane) isolated evals — ONE lane per eval (designer's wedge
//     warning: chained dual-lane sort/reverse probes hung the engine)
//   - mutating lanes time a fresh clone per run (pre-built pool, clone
//     excluded from timing)
//   - native lane timing = the FULL gated dispatch (classify+pack + DLL op +
//     unpack), exactly what a user pays; gate enabled via
//     ESARR.enableNativeGate({dir, libName}) with the shipped ESARRArray.dll
//     (byte+1 wire); bands widened to [1,48000] for measurement (the win-band
//     table derives from the DATA, not the default bands)
//   - fixture: mixedFull (LCG ints across [-2^31+1, 2^31-1], seed 987654321 —
//     the native-lane payload fixture, baseline §5) + asc for reverse/join
//   - NEVER pack >= 48k elements (wedge cap); 48k = hard upper band edge
//   - per-eval raw JSON checkpoint + bench/status.json resume markers
//
// Outputs: bench/round1-raw-<size>-<lane>.json (per eval), bench/status.json
// (resume), merged tables -> esarr/docs/benchmark-rounds-1.md
